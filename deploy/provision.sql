\set ON_ERROR_STOP on

BEGIN;
CREATE ROLE pgfacade_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE pgfacade_reader NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE pgfacade_writer NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE pgfacade LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS CONNECTION LIMIT 12 PASSWORD NULL;
GRANT pgfacade_reader, pgfacade_writer TO pgfacade WITH ADMIN FALSE, INHERIT FALSE, SET TRUE;
ALTER ROLE pgfacade SET statement_timeout = '10s';
ALTER ROLE pgfacade SET lock_timeout = '2s';
ALTER ROLE pgfacade SET idle_in_transaction_session_timeout = '30s';
ALTER ROLE pgfacade SET temp_file_limit = '128MB';
COMMIT;

CREATE DATABASE pgfacade OWNER pgfacade_owner;
REVOKE ALL ON DATABASE pgfacade FROM PUBLIC;
GRANT CONNECT ON DATABASE pgfacade TO pgfacade;
ALTER ROLE pgfacade IN DATABASE pgfacade SET search_path = pg_catalog, app;

\connect pgfacade
BEGIN;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA app AUTHORIZATION pgfacade_owner;
GRANT USAGE ON SCHEMA app TO pgfacade_reader, pgfacade_writer;
ALTER DEFAULT PRIVILEGES FOR ROLE pgfacade_owner IN SCHEMA app GRANT SELECT ON TABLES TO pgfacade_reader;
ALTER DEFAULT PRIVILEGES FOR ROLE pgfacade_owner IN SCHEMA app GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO pgfacade_writer;
ALTER DEFAULT PRIVILEGES FOR ROLE pgfacade_owner IN SCHEMA app GRANT USAGE, SELECT ON SEQUENCES TO pgfacade_writer;
ALTER DEFAULT PRIVILEGES FOR ROLE pgfacade_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
COMMIT;
