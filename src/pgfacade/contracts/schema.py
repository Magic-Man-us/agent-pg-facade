class ColumnAlterInput(Contract):
    table: TableName
    column: Name
    type: SqlType | None = None
    using: SqlBody | None = Field(None, description="Conversion expression, e.g. 'col::integer' (needs sql permission)")
    default: JsonValue = None
    default_expr: DefaultExpr | None = None
    drop_default: OperationFlag = False
    nullable: OperationFlag | None = None
    comment: ObjectComment | None = None

    @model_validator(mode="after")
    def _not_empty(self) -> ColumnAlterInput:
        if not any(
            [self.type, self.default is not None, self.default_expr, self.drop_default, self.nullable is not None, self.comment is not None]
        ):
            raise ValueError("nothing to alter")
        if self.using and not self.type:
            raise ValueError("using requires type")
        return self


