class TableCreateInput(Contract):
    table: TableName
    columns: NonEmptyItems[ColumnSpec]
    primary_key: list[Name] = Field(default_factory=list)
    if_not_exists: OperationFlag = True
    comment: ObjectComment | None = None

    @model_validator(mode="after")
    def _one_pk_style(self) -> TableCreateInput:
        inline = [c.name for c in self.columns if c.primary_key]
        if inline and self.primary_key:
            raise ValueError("use column-level primary_key or table-level primary_key, not both")
        if len(inline) > 1:
            raise ValueError("multiple column-level primary keys; use table-level primary_key for composite keys")
        return self


