class ViewCreateInput(Contract):
    name: TableName
    query: SqlStatement
    materialized: OperationFlag = False
    replace: OperationFlag = Field(False, description="CREATE OR REPLACE (plain views only)")
    with_data: OperationFlag = Field(True, description="Materialized only; false creates it empty")

    @model_validator(mode="after")
    def validate_view_options(self) -> Self:
        if self.materialized and self.replace:
            raise ValueError("materialized views cannot use CREATE OR REPLACE; drop and recreate")
        return self


