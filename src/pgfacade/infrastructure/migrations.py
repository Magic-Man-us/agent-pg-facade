"""migration.* handlers: Alembic driven programmatically (no alembic.ini).

Migrations run as the connector user through Alembic's own SQLAlchemy connection, not under the
caller's SET ROLE. Revision files are plain SQL wrapped in op.execute().
"""

from __future__ import annotations

import io
from typing import TYPE_CHECKING

from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.script.revision import ResolutionError
from alembic.util import rev_id
from sqlalchemy import create_engine

from pgfacade.application.errors import InvalidRequest, NotFound
from pgfacade.contracts.admin import (
    MigrationOutcome,
    MigrationRevisionInput,
    MigrationStatus,
    RevisionInfo,
)
from pgfacade.contracts.enums import MigrationAction
from pgfacade.contracts.types import MigrationDirectory, OperationFlag, RevisionId, SqlBody

if TYPE_CHECKING:
    from pgfacade.infrastructure.postgres.engine import Core
from pgfacade.shared.types import DatabaseConnectionString, SqlAlchemyUrl

_ENV_PY = '''"""Alembic environment generated by pgfacade. The URL is injected at runtime."""

from alembic import context
from sqlalchemy import engine_from_config, pool

config = context.config


def run_migrations_offline() -> None:
    context.configure(url=config.get_main_option("sqlalchemy.url"), literal_binds=True, dialect_opts={"paramstyle": "named"})
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(config.get_section(config.config_ini_section, {}), prefix="sqlalchemy.", poolclass=pool.NullPool)
    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=None, transaction_per_migration=True)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
'''

_SCRIPT_MAKO = '''"""${message}

Revision ID: ${up_revision}
Revises: ${down_revision | comma,n}
Create Date: ${create_date}
"""

from collections.abc import Sequence

from alembic import op

revision: str = ${repr(up_revision)}
down_revision: str | Sequence[str] | None = ${repr(down_revision)}
branch_labels: str | Sequence[str] | None = ${repr(branch_labels)}
depends_on: str | Sequence[str] | None = ${repr(depends_on)}


def upgrade() -> None:
    ${upgrades if upgrades else "pass"}


def downgrade() -> None:
    ${downgrades if downgrades else "pass"}
'''


def _sqlalchemy_url(dsn: DatabaseConnectionString) -> SqlAlchemyUrl:
    for prefix in ("postgresql://", "postgres://"):
        if dsn.startswith(prefix):
            return "postgresql+psycopg://" + dsn.removeprefix(prefix)
    if "://" not in dsn:
        raise InvalidRequest("migrations need a URL-style DSN (postgresql://...), not a key=value string")
    return dsn


class AlembicBackend:
    """Synchronous Alembic plumbing; every public call runs it in a worker thread."""

    def __init__(self, db: Core) -> None:
        self.directory: MigrationDirectory = db.settings.migrations_dir
        self.url = _sqlalchemy_url(db.settings.dsn.get_secret_value())

    @property
    def initialized(self) -> OperationFlag:
        return (self.directory / "env.py").exists()

    def config(self) -> Config:
        if not self.initialized:
            raise NotFound(f"migrations directory {self.directory} is not initialized; run migration.init")
        cfg = Config(stdout=io.StringIO())
        cfg.set_main_option("script_location", str(self.directory))
        cfg.set_main_option("sqlalchemy.url", self.url.replace("%", "%%"))  # configparser interpolation
        return cfg

    def current(self) -> list[RevisionId]:
        engine = create_engine(self.url)
        try:
            with engine.connect() as conn:
                return list(MigrationContext.configure(conn).get_current_heads())
        finally:
            engine.dispose()

    def applied(self, script: ScriptDirectory, current: list[RevisionId]) -> set[RevisionId]:
        """Revisions at or below the database's current heads. Heads this checkout does not know (stamped
        elsewhere) yield an empty set rather than an error, so status still answers."""
        if not current:
            return set()
        try:
            return {r.revision for r in script.iterate_revisions(tuple(current), "base")}
        except ResolutionError:
            return set()

    def status(self) -> MigrationStatus:
        if not self.initialized:
            return MigrationStatus(
                directory=self.directory,  # type: ignore[arg-type]  # DirectoryName validates Path inputs.
                initialized=False,
                current=[],
                heads=[],
                up_to_date=False,
                pending=[],
            )
        script = ScriptDirectory.from_config(self.config())
        current = self.current()
        heads = list(script.get_heads())
        applied = self.applied(script, current)
        pending = [r.revision for r in reversed(list(script.walk_revisions())) if r.revision not in applied]
        return MigrationStatus(
            directory=self.directory,  # type: ignore[arg-type]  # DirectoryName validates Path inputs.
            initialized=True,
            current=current,
            heads=heads,
            up_to_date=set(current) == set(heads),
            pending=pending,
        )

    def history(self) -> list[RevisionInfo]:
        script = ScriptDirectory.from_config(self.config())
        current = self.current()
        applied = self.applied(script, current)
        return [
            RevisionInfo.model_validate(revision, from_attributes=True).model_copy(update={"applied": revision.revision in applied})
            for revision in reversed(list(script.walk_revisions()))
        ]

    def revision(self, req: MigrationRevisionInput) -> RevisionInfo:
        def body(statement: SqlBody | None) -> SqlBody:
            return f"op.execute({statement!r})" if statement else ""

        script = ScriptDirectory.from_config(self.config())
        created = script.generate_revision(
            rev_id(), req.message, head="head", refresh=True, upgrades=body(req.upgrade_sql), downgrades=body(req.downgrade_sql)
        )
        if created is None:
            raise InvalidRequest("alembic did not create a revision")
        return RevisionInfo.model_validate(created, from_attributes=True)

    def run(self, action: MigrationAction, target: RevisionId) -> MigrationOutcome:
        cfg = self.config()
        before = self.current()
        {MigrationAction.UPGRADE: command.upgrade, MigrationAction.DOWNGRADE: command.downgrade, MigrationAction.STAMP: command.stamp}[
            action
        ](cfg, target)
        out = cfg.stdout.getvalue() if isinstance(cfg.stdout, io.StringIO) else ""
        return MigrationOutcome(before=before, after=self.current(), output=out)

    def init(self) -> MigrationStatus:
        (self.directory / "versions").mkdir(parents=True, exist_ok=True)
        if not (self.directory / "env.py").exists():
            (self.directory / "env.py").write_text(_ENV_PY)
        if not (self.directory / "script.py.mako").exists():
            (self.directory / "script.py.mako").write_text(_SCRIPT_MAKO)
        return self.status()
