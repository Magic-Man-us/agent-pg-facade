
CREATE SCHEMA IF NOT EXISTS _pgfacade;

CREATE TABLE IF NOT EXISTS _pgfacade.lifecycle_policies (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          text NOT NULL CHECK (kind IN ('row_ttl', 'table_expiry')),
    schema_name   text NOT NULL,
    table_name    text NOT NULL,
    column_name   text,
    ttl           interval,
    expires_at    timestamptz,
    action        text NOT NULL,
    archive_table text,
    batch_size    int  NOT NULL DEFAULT 5000,
    enabled       bool NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_run_at   timestamptz,
    last_rows     bigint,
    last_error    text,
    UNIQUE NULLS NOT DISTINCT (kind, schema_name, table_name, column_name)
);
ALTER TABLE _pgfacade.lifecycle_policies ADD COLUMN IF NOT EXISTS archive_table text;
ALTER TABLE _pgfacade.lifecycle_policies DROP CONSTRAINT IF EXISTS lifecycle_policies_action_check;
ALTER TABLE _pgfacade.lifecycle_policies
    ADD CONSTRAINT lifecycle_policies_action_check CHECK (action IN ('delete', 'archive', 'truncate', 'drop'));

CREATE TABLE IF NOT EXISTS _pgfacade.lifecycle_runs (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    policy_id     bigint NOT NULL,
    table_name    text NOT NULL,
    action        text NOT NULL,
    started_at    timestamptz NOT NULL,
    finished_at   timestamptz NOT NULL,
    rows_affected bigint NOT NULL,
    error         text
);
CREATE INDEX IF NOT EXISTS lifecycle_runs_policy_idx ON _pgfacade.lifecycle_runs (policy_id, id DESC);

CREATE OR REPLACE FUNCTION _pgfacade.run_lifecycle(p_id bigint DEFAULT NULL)
RETURNS TABLE (policy_id bigint, rows_affected bigint, error text)
LANGUAGE plpgsql AS $fn$
DECLARE
    p       record;
    n       bigint;
    total   bigint;
    started timestamptz;
    cond    text;
    cols    text;
BEGIN
    DELETE FROM _pgfacade.lifecycle_runs WHERE started_at < now() - interval '30 days';
    FOR p IN SELECT * FROM _pgfacade.lifecycle_policies
             WHERE enabled AND (p_id IS NULL OR id = p_id) ORDER BY id
    LOOP
        total := 0; error := NULL; started := clock_timestamp();
        BEGIN
            IF p.kind = 'row_ttl' THEN
                cond := CASE WHEN p.ttl IS NULL THEN format('%I <= now()', p.column_name)
                             ELSE format('%I <= now() - %L::interval', p.column_name, p.ttl) END;
                IF p.action = 'archive' THEN
                    -- The table's current columns, so an archive table with extra columns (archived_at) still fits.
                    SELECT string_agg(quote_ident(attname), ', ' ORDER BY attnum) INTO cols
                    FROM pg_attribute
                    WHERE attrelid = format('%I.%I', p.schema_name, p.table_name)::regclass AND attnum > 0 AND NOT attisdropped;
                END IF;
                LOOP
                    IF p.action = 'archive' THEN
                        EXECUTE format(
                            'WITH d AS (SELECT ctid FROM %I.%I WHERE %s LIMIT %s), '
                            'moved AS (DELETE FROM %I.%I t USING d WHERE t.ctid = d.ctid RETURNING t.*) '
                            'INSERT INTO %s (%s) SELECT %s FROM moved',
                            p.schema_name, p.table_name, cond, p.batch_size, p.schema_name, p.table_name,
                            p.archive_table, cols, cols);
                    ELSE
                        EXECUTE format(
                            'WITH d AS (SELECT ctid FROM %I.%I WHERE %s LIMIT %s) '
                            'DELETE FROM %I.%I t USING d WHERE t.ctid = d.ctid',
                            p.schema_name, p.table_name, cond, p.batch_size, p.schema_name, p.table_name);
                    END IF;
                    GET DIAGNOSTICS n = ROW_COUNT;
                    total := total + n;
                    EXIT WHEN n < p.batch_size;
                END LOOP;
            ELSIF p.expires_at <= now() THEN
                IF p.action = 'drop' THEN
                    EXECUTE format('DROP TABLE IF EXISTS %I.%I', p.schema_name, p.table_name);
                ELSE
                    EXECUTE format('TRUNCATE %I.%I', p.schema_name, p.table_name);
                END IF;
                UPDATE _pgfacade.lifecycle_policies SET enabled = false WHERE id = p.id;
                total := 1;
            ELSE
                CONTINUE;
            END IF;
        EXCEPTION WHEN OTHERS THEN
            error := SQLERRM;
        END;
        UPDATE _pgfacade.lifecycle_policies
           SET last_run_at = now(), last_rows = total, last_error = error WHERE id = p.id;
        INSERT INTO _pgfacade.lifecycle_runs (policy_id, table_name, action, started_at, finished_at, rows_affected, error)
        VALUES (p.id, p.schema_name || '.' || p.table_name, p.action, started, clock_timestamp(), total, error);
        IF total > 0 OR error IS NOT NULL THEN
            PERFORM pg_notify({channel}, json_build_object(
                'event', CASE WHEN error IS NULL THEN 'lifecycle.run' ELSE 'lifecycle.error' END,
                'policy_id', p.id, 'table', p.schema_name || '.' || p.table_name, 'action', p.action,
                'rows_affected', total, 'error', error, 'at', now())::text);
        END IF;
        policy_id := p.id; rows_affected := total;
        RETURN NEXT;
    END LOOP;
END
$fn$;
