from dataclasses import dataclass
from typing import TYPE_CHECKING

from psycopg import sql
from pydantic import JsonValue

from pgfacade.contracts.base import DefaultExpr
from pgfacade.contracts.enums import ConstraintKind, TableOrder
from pgfacade.contracts.schema import (
    CheckConstraintInput,
    ColumnAdd,
    ColumnAlter,
    ColumnDrop,
    ColumnRename,
    ColumnSpec,
    ConstraintAdd,
    ConstraintDrop,
    ExtensionCreate,
    ExtensionDrop,
    IndexCreate,
    IndexDrop,
    SchemaCreate,
    SchemaDrop,
    TableCreate,
    TableDrop,
    TableList,
    TableRename,
    TableTruncate,
    ViewCreate,
    ViewDrop,
    ViewRefresh,
)
from pgfacade.contracts.types import Name, ObjectComment

if TYPE_CHECKING:
    from pgfacade.infrastructure.postgres.engine import Core
from pgfacade.infrastructure.postgres.queries import Statement
from pgfacade.infrastructure.postgres.queries.composition import Binder, TableMeta, flag, kw, literal, text, truncate_name


@dataclass(frozen=True, slots=True)
class NamedStatement:
    name: Name
    statement: sql.Composed


def _default_sql(default: JsonValue, default_expr: DefaultExpr | None) -> sql.Composable:
    if default_expr is not None:
        return sql.SQL(" DEFAULT {}").format(kw(default_expr))
    return sql.SQL(" DEFAULT {}").format(literal(default))


def _column_def(db: Core, c: ColumnSpec) -> sql.Composable:
    parts: list[sql.Composable] = [sql.Identifier(c.name), kw(c.type)]
    if c.identity:
        parts.append(sql.SQL("GENERATED BY DEFAULT AS IDENTITY"))
    if c.primary_key:
        parts.append(sql.SQL("PRIMARY KEY"))
    if not c.nullable:
        parts.append(sql.SQL("NOT NULL"))
    if c.unique:
        parts.append(sql.SQL("UNIQUE"))
    if c.default_expr is not None or c.default is not None:
        parts.append(_default_sql(c.default, c.default_expr))
    if c.references is not None:
        ref = c.references
        parts.append(sql.SQL("REFERENCES {} ({})").format(db.qualified(ref.table), sql.Identifier(ref.column)))
        if ref.on_delete is not None:
            parts.append(sql.SQL("ON DELETE {}").format(kw(ref.on_delete.upper())))
    return sql.SQL(" ").join(parts)


def comment(ident: sql.Identifier, comment: ObjectComment | None, column: Name | None = None) -> sql.Composed:
    target = sql.SQL("COLUMN {}.{}").format(ident, sql.Identifier(column)) if column else sql.SQL("TABLE {}").format(ident)
    return Statement.SCHEMA_COMMENT.sql.format(target, sql.Literal(comment))


def create_schema(db: Core, req: SchemaCreate) -> sql.Composed:
    query = Statement.SCHEMA_SCHEMA_CREATE.sql.format(
        ine=flag(req.input.if_not_exists, "IF NOT EXISTS "),
        name=sql.Identifier(req.input.name),
        owner=sql.SQL(" AUTHORIZATION {}").format(sql.Identifier(req.input.owner)) if req.input.owner else sql.SQL(""),
    )
    return query


def drop_schema(db: Core, req: SchemaDrop) -> sql.Composed:
    query = Statement.SCHEMA_SCHEMA_DROP.sql.format(
        flag(req.input.if_exists, "IF EXISTS "), sql.Identifier(req.input.name), flag(req.input.cascade, " CASCADE")
    )
    return query


def list_tables(req: TableList) -> sql.Composed:
    scope = sql.SQL("n.nspname = %s") if req.input.schema_name else sql.SQL("n.nspname !~ '^pg_' AND n.nspname <> 'information_schema'")
    query = Statement.SCHEMA_TABLES.sql.format(
        cond=sql.SQL("c.relkind IN ('r','p','v','m','f') AND NOT c.relispartition AND ") + scope,
        order=sql.SQL("total_bytes DESC" if req.input.order == TableOrder.SIZE else "1, 2"),
        limit=sql.SQL(" LIMIT {}").format(sql.Literal(req.input.limit)) if req.input.limit else sql.SQL(""),
    )
    return query


def drop_table(db: Core, req: TableDrop) -> sql.Composed:
    query = Statement.SCHEMA_TABLE_DROP.sql.format(
        flag(req.input.if_exists, "IF EXISTS "), db.qualified(req.input.table), flag(req.input.cascade, " CASCADE")
    )
    return query


def rename_table(db: Core, req: TableRename) -> sql.Composed:
    query = Statement.SCHEMA_TABLE_RENAME.sql.format(db.qualified(req.input.table), sql.Identifier(req.input.new_name))
    return query


def truncate_table(db: Core, req: TableTruncate) -> sql.Composed:
    query = Statement.SCHEMA_TABLE_TRUNCATE.sql.format(
        db.qualified(req.input.table), flag(req.input.restart_identity, " RESTART IDENTITY"), flag(req.input.cascade, " CASCADE")
    )
    return query


def drop_column(db: Core, req: ColumnDrop) -> sql.Composed:
    query = Statement.SCHEMA_COLUMN_DROP.sql.format(
        db.qualified(req.input.table),
        flag(req.input.if_exists, "IF EXISTS "),
        sql.Identifier(req.input.column),
        flag(req.input.cascade, " CASCADE"),
    )
    return query


def drop_constraint(db: Core, req: ConstraintDrop) -> sql.Composed:
    query = Statement.SCHEMA_CONSTRAINT_DROP.sql.format(
        db.qualified(req.input.table),
        flag(req.input.if_exists, "IF EXISTS "),
        sql.Identifier(req.input.name),
        flag(req.input.cascade, " CASCADE"),
    )
    return query


def drop_index(db: Core, req: IndexDrop) -> sql.Composed:
    query = Statement.SCHEMA_INDEX_DROP.sql.format(
        flag(req.input.concurrently, "CONCURRENTLY "),
        flag(req.input.if_exists, "IF EXISTS "),
        db.qualified(req.input.index),
        flag(req.input.cascade, " CASCADE"),
    )
    return query


def create_view(db: Core, req: ViewCreate) -> sql.Composed:
    query = Statement.SCHEMA_VIEW_CREATE.sql.format(
        replace=flag(req.input.replace, "OR REPLACE "),
        mat=flag(req.input.materialized, "MATERIALIZED "),
        name=db.qualified(req.input.name),
        body=text(req.input.query),
        data=sql.SQL("" if not req.input.materialized else (" WITH DATA" if req.input.with_data else " WITH NO DATA")),
    )
    return query


def drop_view(db: Core, req: ViewDrop) -> sql.Composed:
    query = Statement.SCHEMA_VIEW_DROP.sql.format(
        flag(req.input.materialized, "MATERIALIZED "),
        flag(req.input.if_exists, "IF EXISTS "),
        db.qualified(req.input.name),
        flag(req.input.cascade, " CASCADE"),
    )
    return query


def refresh_view(db: Core, req: ViewRefresh) -> sql.Composed:
    query = Statement.SCHEMA_VIEW_REFRESH.sql.format(flag(req.input.concurrently, "CONCURRENTLY "), db.qualified(req.input.name))
    return query


def create_extension(req: ExtensionCreate) -> sql.Composed:
    query = Statement.SCHEMA_EXTENSION_CREATE.sql.format(
        sql.Identifier(req.input.name),
        sql.SQL(" SCHEMA {}").format(sql.Identifier(req.input.schema_name)) if req.input.schema_name else sql.SQL(""),
        sql.SQL(" VERSION {}").format(sql.Literal(req.input.version)) if req.input.version else sql.SQL(""),
        flag(req.input.cascade, " CASCADE"),
    )
    return query


def drop_extension(req: ExtensionDrop) -> sql.Composed:
    query = Statement.SCHEMA_EXTENSION_DROP.sql.format(
        flag(req.input.if_exists, "IF EXISTS "), sql.Identifier(req.input.name), flag(req.input.cascade, " CASCADE")
    )
    return query


def describe_table() -> sql.Composed:
    return Statement.SCHEMA_TABLES.sql.format(cond=sql.SQL("c.oid = to_regclass(%s)"), order=sql.SQL("1"), limit=sql.SQL(""))


def create_table(db: Core, req: TableCreate) -> sql.Composed:
    defs = [_column_def(db, column) for column in req.input.columns]
    if req.input.primary_key:
        defs.append(sql.SQL("PRIMARY KEY ({})").format(sql.SQL(", ").join([sql.Identifier(column) for column in req.input.primary_key])))
    return Statement.SCHEMA_TABLE_CREATE.sql.format(
        ine=flag(req.input.if_not_exists, "IF NOT EXISTS "), table=db.qualified(req.input.table), defs=sql.SQL(", ").join(defs)
    )


def add_column(db: Core, req: ColumnAdd) -> sql.Composed:
    return Statement.SCHEMA_COLUMN_ADD.sql.format(
        db.qualified(req.input.table), flag(req.input.if_not_exists, "IF NOT EXISTS "), _column_def(db, req.input.column)
    )


def alter_column(meta: TableMeta, req: ColumnAlter) -> sql.Composed | None:
    col = Binder(meta).col(req.input.column)
    actions: list[sql.Composable] = []
    if req.input.type is not None:
        using = (sql.SQL(" USING ") + text(req.input.using)) if req.input.using else sql.SQL("")
        actions.append(Statement.SCHEMA_COLUMN_TYPE.sql.format(col, kw(req.input.type), using))
    if req.input.drop_default:
        actions.append(Statement.SCHEMA_COLUMN_DROP_DEFAULT.sql.format(col))
    elif req.input.default is not None or req.input.default_expr is not None:
        actions.append(Statement.SCHEMA_COLUMN_SET_DEFAULT.sql.format(col, _default_sql(req.input.default, req.input.default_expr)))
    if req.input.nullable is not None:
        actions.append(Statement.SCHEMA_COLUMN_NULLABLE.sql.format(col, sql.SQL("DROP" if req.input.nullable else "SET")))
    return Statement.SCHEMA_COLUMN_ALTER.sql.format(meta.ident, sql.SQL(", ").join(actions)) if actions else None


def rename_column(meta: TableMeta, req: ColumnRename) -> sql.Composed:
    return Statement.SCHEMA_COLUMN_RENAME.sql.format(meta.ident, Binder(meta).col(req.input.column), sql.Identifier(req.input.new_name))


def add_constraint(db: Core, meta: TableMeta, req: ConstraintAdd) -> NamedStatement:
    b = Binder(meta)
    columns = [] if isinstance(req.input, CheckConstraintInput) else req.input.columns
    cols = sql.SQL(", ").join([b.col(column) for column in columns])
    suffix = {
        ConstraintKind.UNIQUE: "key",
        ConstraintKind.PRIMARY_KEY: "pkey",
        ConstraintKind.FOREIGN_KEY: "fkey",
        ConstraintKind.CHECK: "check",
    }[req.input.kind]
    name = req.input.name or truncate_name(f"{meta.name}_{'_'.join(columns) or 'expr'}_{suffix}")
    match req.input.kind:
        case ConstraintKind.UNIQUE:
            body = sql.SQL("UNIQUE ({})").format(cols)
        case ConstraintKind.PRIMARY_KEY:
            body = sql.SQL("PRIMARY KEY ({})").format(cols)
        case ConstraintKind.FOREIGN_KEY:
            ref = req.input.references
            assert ref is not None
            body = sql.SQL("FOREIGN KEY ({}) REFERENCES {} ({})").format(cols, db.qualified(ref.table), sql.Identifier(ref.column))
            if ref.on_delete is not None:
                body = body + sql.SQL(" ON DELETE {}").format(kw(ref.on_delete.upper()))
        case _:
            body = sql.SQL("CHECK ({})").format(text(req.input.expression))
    return NamedStatement(name=name, statement=Statement.SCHEMA_CONSTRAINT_ADD.sql.format(meta.ident, sql.Identifier(name), body))


def create_index(meta: TableMeta, req: IndexCreate) -> NamedStatement:
    b = Binder(meta)
    name = req.input.name or truncate_name(f"{meta.name}_{'_'.join(req.input.columns)}_{'key' if req.input.unique else 'idx'}")
    query = Statement.SCHEMA_INDEX_CREATE.sql.format(
        unique=flag(req.input.unique, "UNIQUE "),
        cc=flag(req.input.concurrently, "CONCURRENTLY "),
        ine=flag(req.input.if_not_exists, "IF NOT EXISTS "),
        name=sql.Identifier(name),
        table=meta.ident,
        method=kw(req.input.method),
        cols=sql.SQL(", ").join([b.col(column) for column in req.input.columns]),
    )
    return NamedStatement(name=name, statement=query)
